export function translateBanglaText(value: string): string {
  if (!value || !/[\u0980-\u09FF]/.test(value)) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  const core = value.trim();
  const normalized = normalize(core);
  const exact = bnToEn[normalized];
  if (exact) return `${leading}${exact}${trailing}`;

  const dateMatch = normalized.match(
    /^([0-9০-৯]+)\s+(জানুয়ারি|ফেব্রুয়ারি|মার্চ|এপ্রিল|মে|জুন|জুলাই|আগস্ট|সেপ্টেম্বর|অক্টোবর|নভেম্বর|ডিসেম্বর)\s+([0-9০-৯]+),\s*(সকাল|বিকাল\/রাত)\s+([0-9০-৯]+):([0-9০-৯]+)$/
  );
  if (dateMatch) {
    const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
    const monthIndex = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'].indexOf(dateMatch[2]);
    const toAsciiDigits = (digits: string) => digits.replace(/[০-৯]/g, digit => digitMap[digit]);
    const period = dateMatch[4] === 'সকাল' ? 'AM' : 'PM';
    const translatedDate = `${months[monthIndex]} ${toAsciiDigits(dateMatch[1])}, ${toAsciiDigits(dateMatch[3])}, ${toAsciiDigits(dateMatch[5])}:${toAsciiDigits(dateMatch[6])} ${period}`;
    return `${leading}${translatedDate}${trailing}`;
  }

  const relativeTimeMatch = normalized.match(/^([0-9০-৯]+)\s+(দিন|ঘণ্টা|মিনিট)\s+আগে$/);
  if (relativeTimeMatch) {
    const units: Record<string, string> = { দিন: 'days', ঘণ্টা: 'hours', মিনিট: 'minutes' };
    const unit = units[relativeTimeMatch[2]];
    const amount = relativeTimeMatch[1].replace(/[০-৯]/g, digit => digitMap[digit]);
    return `${leading}${amount} ${unit} ago${trailing}`;
  }

  if (normalized === 'এইমাত্র') return `${leading}Just now${trailing}`;

  const overdueMatch = normalized.match(/^এসএলএ\s+সময়\s+অতিক্রান্ত\s+\(([0-9০-৯]+)\s+ঘণ্টা\s+বিলম্ব\)$/);
  if (overdueMatch) {
    const hours = overdueMatch[1].replace(/[০-৯]/g, digit => digitMap[digit]);
    return `${leading}SLA exceeded (${hours} hours overdue)${trailing}`;
  }

  for (const [pattern, replacement] of dynamicRules) {
    if (pattern.test(normalized)) {
      return `${leading}${normalized.replace(pattern, replacement).replace(/[০-৯]/g, digit => digitMap[digit])}${trailing}`;
    }
  }
  let withWords = normalized;
  for (const [bangla, english] of wordMap) {
    const escaped = bangla.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const pattern = new RegExp(`(^|[^\\u0980-\\u09FF])${escaped}(?=$|[^\\u0980-\\u09FF])`, 'g');
    withWords = withWords.replace(pattern, (_match, prefix) => `${prefix}${english}`);
  }
  const withDigits = withWords.replace(/[০-৯]/g, digit => digitMap[digit]);
  return `${leading}${withDigits}${trailing}`;
}
